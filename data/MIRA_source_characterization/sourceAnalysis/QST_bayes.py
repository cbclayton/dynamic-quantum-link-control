def neg(rho, D):
    '''
    

    Parameters
    ----------
    rho : TYPE
        DESCRIPTION.
    D : TYPE
        DESCRIPTION.

    Returns
    -------
    TYPE
        DESCRIPTION.

    '''
    rhoPT = np.zeros((D,D),dtype=complex) # initialize partial transpose
    d = int(np.sqrt(D))
    idx = np.arange(0,d*(d-1)+1,d)
    for r in idx:
        for c in idx:
            rhoPT[r:r+d,c:c+d] = np.transpose(rho[r:r+d,c:c+d])
    lam = np.real(np.linalg.eigvals(rhoPT))

    return -np.dot(lam<0,lam)

