@njit
def neg_alt(rho, D):
    """
    Compute negativity of a density matrix rho (dimension D x D)
    using partial transpose. Numba-compatible version.
    """
    # allocate partial transpose
    rhoPT = np.zeros((D, D), dtype=np.complex128)
    
    d = int(np.sqrt(D))

    # indices for block structure
    # (manual creation since np.arange(start, stop, step) with complex inputs can be tricky)
    idx = np.empty(d, dtype=np.int64)
    for k in range(d):
        idx[k] = k * d

    # partial transpose w.r.t. second subsystem
    for rr in range(d):
        r = idx[rr]
        for cc in range(d):
            c = idx[cc]
            # transpose the d×d block
            for i in range(d):
                for j in range(d):
                    rhoPT[r + i, c + j] = rho[r + j, c + i]

    # eigenvalues (rhoPT is Hermitian)
    lam = np.linalg.eigh(rhoPT)[0].real

    # negativity = sum of |negative eigenvalues|
    neg_sum = 0.0
    for i in range(len(lam)):
        if lam[i] < 0.0:
            neg_sum += -lam[i]

    return neg_sum

