def analyze_samples(counts, K0, M, THIN, bell_choice,samp,rho_ref, Ua, Ub):
    
    D = 4        # Extract Hilbert space dimension
    k = 0.1             # relative st.dev. for counts
    
    num_samp = np.shape(samp)[0]
    
    # Analyze samples
    rhoEst = np.zeros((D, D, num_samp), dtype=complex)
    Kest = np.zeros(num_samp)
    # Eest = np.zeros(num_samp)
    rhoB = np.zeros((D, D), dtype=complex)  #Bayesian mean

    for n in range(num_samp):
        rho_vec = param_to_rho_col(samp[n, :-1], D)
        rho_mat = rho_vec.reshape((D, D)).T.conj() #conjugate needed (for some reason...)
        rhoEst[:, :, n] = rho_mat
        rhoB += rho_mat / num_samp
        
        # negvals = neg(rhoEst[:,:,n],D)
        # Eest[n] = np.log2(2*negvals+1)
        Kest[n] = K0 * (1 + k * samp[n, -1])
    
    if len(Ua) < 1 or len(Ub) < 1:
        Ua, Ub = dmat.beautify_2qubit(rhoB)
    
    # Ucor = kron(Ua, Ub)
    rhoC = dmat.compensate_2qubit(rhoB,Ua,Ub,bell_choice=bell_choice)
    
    rhoBell = dmat.generate_werner_2qubit(bell_choice)
    
    result = {
        'K': np.mean(Kest),
        'dK': np.std(Kest, ddof=1),
        # 'E': np.mean(Eest),
        # 'dE': np.std(Eest, ddof=1),
        'rhoB': rhoB,
        'rhoC': rhoC,
        'samp': samp,
        'THIN': THIN,
        'psi': rhoBell,
        'M': M,
        'Ua': Ua,
        'Ub': Ub,
        'counts': counts
    }
    
    # Fidelity calculations
    
    rho_ref = [rhoBell] + rho_ref
    
    num_refs = len(rho_ref)
    
    Fb = [np.zeros(num_samp) for rho0 in rho_ref]
    Fc = [np.zeros(num_samp) for rho0 in rho_ref]
    
    for i in range(num_refs):
        for n in range(num_samp):
            rho_raw = rhoEst[:, :, n]
            rho_rot = dmat.compensate_2qubit(rho_raw,Ua,Ub,bell_choice=bell_choice)
            
            Fb[i][n] = dmat.compute_fidelity(rho_raw, rho_ref[i])
            Fc[i][n] = dmat.compute_fidelity(rho_rot, rho_ref[i])

        result[f'F{i}b'] = np.mean(Fb[i])
        result[f'F{i}c'] = np.mean(Fc[i])
        result[f'dF{i}b'] = np.std(Fb[i], ddof=1)
        result[f'dF{i}c'] = np.std(Fc[i], ddof=1)

    return result


@njit
def param_to_rho_col(par, D):
    '''
    

    Parameters
    ----------
    par : TYPE
        DESCRIPTION.
    D : TYPE
        DESCRIPTION.

    Returns
    -------
    TYPE
        DESCRIPTION.

    '''
    # Ginibre draws 1 & 2
    G = par[0:D**2].reshape(D, D) + 1j * par[D**2:2*D**2].reshape(D, D)
    H = par[2*D**2:3*D**2].reshape(D, D) + 1j * par[3*D**2:4*D**2].reshape(D, D)
    
    # Find uniray from H (from QETLAB)
    Q, R = np.linalg.qr(H)
    V = Q * np.sign(np.diag(R))[:, np.newaxis]
    W = (np.eye(D) + V) @ G # Bures construction.
    
    rho = W @ W.conj().T
    rho /= np.trace(rho)
    
    return rho.T.flatten()

