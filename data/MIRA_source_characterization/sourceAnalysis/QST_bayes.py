def run_tomography(counts,proj_order,th=9,bell_choice=2,make_plots=False,verbose=False,
                   rho_ref=[], Ua=[], Ub=[]):
    '''
    Run Quantum State Tomography with Bayesian reconstruction algorithm.

    Parameters
    ----------
    data_dir : STRING
        Input data directory.
    data_name : STRING
        Input data filename.
    th : INT, optional
        log2(thinning parameter). The default is 9.
    bell_choice : INT, optional
        Choice of target Bellstate. The default is 2.
            0 --> Phi +
            1 --> Phi -
            2 --> Psi +
            3 --> Psi -
    make_plots : BOOL, optional
        Option to plot raw count data. The default is False.
    rho_mle : Numpy ARRAY, optional
        Reference density matrix generated by MLE. The default is None.
    acc_subtract : BOOL, optional
        Subtract accidentals as input data is read. The default is False.

    Returns
    -------
    result : TYPE
        DESCRIPTION.

    '''
    
    #TODO: include option for 16-projection tomography
    K0 = np.sum(counts)/9
    
    M = meas_matrix(proj_order)
    
    # print(M)

    # Run MCMC
    THIN = 2**th
    
    if verbose:
        start_time = datetime.now()
        
    samp = two_qubit_BP(counts, K0, M, THIN)
    
    if verbose:
        end_time = datetime.now()
        time_delta = end_time - start_time
        print(f"Sampler time: {time_delta.total_seconds()} s")
    
    result = analyze_samples(counts, K0, M, THIN, bell_choice, samp, rho_ref, Ua, Ub)
         
    return result

def meas_matrix(proj_order):
    '''
    Generate measurement matrix from list of polarization state projections.
    Contains map from basis names {H,V,D,A,R,L} onto complex vectors.

    Parameters
    ----------
    proj_order : LIST of pairs of STRINGs
        List of polarization basis state combinations ['a','b'].

    Returns
    -------
    M : NUMPY ARRAY
        Array of projection matrices, representing all listed input measurements.

    '''
    # Define basis kets
    basis = {
        'H': np.array([1, 0], dtype=complex),
        'V': np.array([0, 1], dtype=complex),
        'D': (1/np.sqrt(2)) * np.array([1, 1], dtype=complex),
        'A': (1/np.sqrt(2)) * np.array([1, -1], dtype=complex),
        'R': (1/np.sqrt(2)) * np.array([1, 1j], dtype=complex),
        'L': (1/np.sqrt(2)) * np.array([1, -1j], dtype=complex)
    }

    # Build measurement matrix M
    M = []
    for proj in proj_order:
        ket1 = basis[proj[0]]
        ket2 = basis[proj[1]]
        state = kron(ket1, ket2)
        proj_mat = kron(np.conj(state), state)
        M.append(proj_mat)
    M = np.array(M)
    
    return M

@njit
def two_qubit_BP(counts, K0, M, THIN):
    '''
    Main loop for Bayesian estimation.

    Parameters
    ----------
    counts : TYPE
        DESCRIPTION.
    K0 : TYPE
        DESCRIPTION.
    M : TYPE
        DESCRIPTION.
    psi : TYPE
        DESCRIPTION.
    THIN : TYPE
        DESCRIPTION.
    bell_choice : TYPE
        DESCRIPTION.
    rho_mle : TYPE
        DESCRIPTION.

    Returns
    -------
    result : TYPE
        DESCRIPTION.

    '''
    
    ##############################
    # INPUTS
    num_samp = 2**10    # Number of samples to obtain from MH
    D = 4               # Hilbert space dimension
    k = 0.1             # relative st.dev. for counts
    beta = 0.1          # initial stepsize
    
    Mb = 500            # Update stepsize after this many points
    r = 1.1             # Acceptance rate update factor
    
    ##############################
    # INITIAL VALUES FOR SAMPLER
    # np.random.seed()
    param0 = np.random.randn(4*D**2 + 1)
    
    ##############################
    # MH SAMPLER    
    # start_time = datetime.now()
    samp = np.zeros((num_samp, len(param0)))
    acc = 0

    # Initial point:
    x = param0
    rhoX = param_to_rho_col(x[:-1], D)
    Kx = K0 * (1 + k * x[-1])           # Flux value
    pr = np.real(M @ rhoX)              # probabilities
    logX = -Kx * np.sum(pr) + \
            np.dot(counts, np.log(Kx * pr)) #Likelihood

    samp_idx = 0
    for j in range(num_samp * THIN):
        # Proposed update parameters:
        y = np.sqrt(1 - beta**2) * x + beta * np.random.randn(len(x))
        rhoY = param_to_rho_col(y[:-1], D)
        Ky = K0 * (1 + k * y[-1])
        
        pr = np.real(M @ rhoY)
        logY = -Ky * np.sum(pr) + np.dot(counts, np.log(Ky * pr)) # New likelihood

        if np.log(np.random.rand()) < logY - logX:
            x = y           #Accept new point
            logX = logY
            acc += 1

        if (j + 1) % Mb == 0:       # Stepsize adaptation
            rat = acc / Mb          # Est. accept prob., keep near 0.234
            if rat > 0.6:
                beta = min(beta * r, 1.0)   #Cap beta at unity
            elif rat < 0.2:         
                beta /= r
            acc = 0

        if (j + 1) % THIN == 0: #Store samples
            samp[samp_idx] = x
            samp_idx += 1
            
    # end_time = datetime.now()
    
    return samp

